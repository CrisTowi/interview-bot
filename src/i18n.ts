const DICTS: Record<Lang, Dict> = { es, en };

/** UI strings for the current app language; re-renders when it changes. */
export function useT(): Dict {
  return DICTS[useApp((s) => s.settings.uiLang)];
}

/** For code outside React (errors thrown from sync, CV parsing…). */
export function t(): Dict {
  return DICTS[useApp.getState().settings.uiLang];
}

export function capitalize(text: string): string {
  return text ? text[0].toUpperCase() + text.slice(1) : text;
}
